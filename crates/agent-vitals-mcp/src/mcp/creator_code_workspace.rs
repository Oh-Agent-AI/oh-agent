pub(crate) fn file_read(args: &Value, data_home: &Path) -> Result<Value, ToolError> {
    // PR09 候选隔离层：带 `candidateId` 时路径解析进候选树，不触碰基线；
    // 不带时保持基线行为逐字节不变。
    if args.get("candidateId").is_some() {
        return super::creator_code_candidate::candidate_file_read(args, data_home);
    }
    let workspace_id = workspace_id_arg(args)?;
    let relative = safe_relative_path(args)?;
    let directory = workspace_dir(data_home, &workspace_id)?;
    let meta = read_meta(&directory)?;
    let path = resolve_inside(&directory, &relative)?;
    let bytes = std::fs::read(&path).map_err(|_| ToolError::new("not_found", "No such file in this workspace."))?;
    if bytes.len() > MAX_FILE_BYTES {
        return Err(ToolError::new("invalid_argument", "File exceeds the 64 KiB read budget."));
    }
    let content = String::from_utf8(bytes).map_err(|_| ToolError::new("invalid_argument", "Only UTF-8 text files can be read."))?;
    Ok(json!({"ok":true,"data":{
        "workspaceId": meta.workspace_id,
        "relativePath": relative,
        "gameRevision": meta.revision,
        "sha256": sha256_hex(content.as_bytes()),
        "content": content,
    }}))
}

pub(crate) fn file_write(args: &Value, data_home: &Path) -> Result<Value, ToolError> {
    // PR09 候选隔离层：带 `candidateId` 时写入候选树（CAS 对候选 revision，
    // 不取基线写锁）；不带时保持基线行为逐字节不变。
    if args.get("candidateId").is_some() {
        return super::creator_code_candidate::candidate_file_write(args, data_home);
    }
    let workspace_id = workspace_id_arg(args)?;
    let relative = safe_relative_path(args)?;
    if !is_writable_text_path(&relative) {
        return Err(ToolError::new("invalid_argument", "Only .ts/.tsx/.js/.mjs/.json/.md/.txt/.css/.html files can be written."));
    }
    let content = args.get("content").and_then(Value::as_str)
        .ok_or_else(|| ToolError::new("invalid_argument", "`content` must be a string"))?;
    if content.len() > MAX_WRITE_BYTES {
        return Err(ToolError::new("invalid_argument", "Content exceeds the 256 KiB write budget."));
    }
    if relative.split('/').any(|part| matches!(part, "dist" | "node_modules" | ".git" | META_FILE | ".code-game-tsconfig.json")) {
        return Err(ToolError::new("invalid_argument", "Workspace metadata is host-owned and cannot be written."));
    }
    let directory = workspace_dir(data_home, &workspace_id)?;
    // Serialize the compare-and-write across independent MCP processes.
    let locks = data_home.join("code-games").join("workspace-write-locks");
    std::fs::create_dir_all(&locks).map_err(|_| ToolError::new("storage_unavailable", "Cannot open the workspace write lock."))?;
    let mut lock = rusqlite::Connection::open(locks.join(format!("{workspace_id}.sqlite")))
        .map_err(|_| ToolError::new("storage_unavailable", "Cannot open the workspace write lock."))?;
    let _write_lock = lock.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
        .map_err(|_| ToolError::new("busy", "Another write is in progress for this workspace."))?;
    let mut meta = read_meta(&directory)?;
    if let Some(expected) = args.get("expectedRevision").and_then(Value::as_str) {
        if expected != meta.revision {
            return Err(ToolError::new(
                "workspace_revision_conflict",
                "The workspace changed since you read it; re-read workspace info or the file and retry.",
            ));
        }
    }
    let path = resolve_inside(&directory, &relative)?;
    let files = list_files(&directory)?;
    let existing_size = files.iter().find(|(name, _)| name == &relative).map(|(_, size)| *size);
    if existing_size.is_none() && files.len() >= MAX_FILES {
        return Err(ToolError::new("invalid_argument", "The Code Game workspace exceeds the file count budget."));
    }
    let new_size = files.iter().map(|(_, size)| *size).sum::<u64>() - existing_size.unwrap_or(0) + content.len() as u64;
    if new_size > MAX_SNAPSHOT_BYTES {
        return Err(ToolError::new("invalid_argument", "The Code Game workspace exceeds the build input byte budget."));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|_| ToolError::new("storage_unavailable", "Cannot create the target directory."))?;
    }
    let staged_file = locks.join(format!("{workspace_id}.pending"));
    std::fs::write(&staged_file, content.as_bytes())
        .map_err(|_| ToolError::new("storage_unavailable", "Cannot stage the workspace file."))?;
    std::fs::rename(&staged_file, &path)
        .map_err(|_| ToolError::new("storage_unavailable", "Cannot write the workspace file."))?;
    meta.revision = digest_workspace(&directory)?;
    write_meta(&directory, &meta)?;
    Ok(json!({"ok":true,"data":{
        "workspaceId": meta.workspace_id,
        "relativePath": relative,
        "gameRevision": meta.revision,
        "sha256": sha256_hex(content.as_bytes()),
    }}))
}

fn build(args: &Value, data_home: &Path) -> Result<Value, ToolError> {
    let workspace_id = workspace_id_arg(args)?;
    // PR09 候选隔离层：可选 `candidateId` 构建隔离候选树（sealed sourceRevision
    // 为 `candidate:<candidateId>:<digest>`）；缺席时保持基线路径逐字节不变。
    let candidate = super::creator_code_candidate::build_target(args, data_home, &workspace_id)?;
    let directory = match &candidate {
        Some(target) => target.tree.clone(),
        None => workspace_dir(data_home, &workspace_id)?,
    };
    let meta = read_meta(&workspace_dir(data_home, &workspace_id)?)?;
    let revision = match &candidate {
        Some(target) => target.revision.clone(),
        None => meta.revision.clone(),
    };
    if let Some(expected) = args.get("expectedRevision").and_then(Value::as_str) {
        if expected != revision {
            return Err(ToolError::new(
                "workspace_revision_conflict",
                "The workspace changed since you read it; build the revision you actually inspected.",
            ));
        }
    }
    if let Some(target) = &candidate {
        super::creator_code_candidate::mark_status(data_home, &target.candidate_id, "building")?;
    }
    let snapshot = WorkspaceBuildSnapshot::capture(&directory, &revision)?;
    let repo = repo_root()?;
    let out_dir = data_home.join("code-games").join("builds");
    let mut runner_args = vec![
        "--workspace".to_string(),
        snapshot.path.to_string_lossy().to_string(),
    ];
    // builder CLI 只接受 workspace/candidate 两种密封身份之一；候选构建不携带
    // workspace-id，防止候选构建被基线消费者（preview/CAS 校验）误认。
    match &candidate {
        Some(target) => {
            runner_args.push("--candidate-id".to_string());
            runner_args.push(target.candidate_id.clone());
        }
        None => {
            runner_args.push("--workspace-id".to_string());
            runner_args.push(meta.workspace_id.clone());
        }
    }
    runner_args.extend([
        "--source-revision".to_string(),
        revision.clone(),
        "--out".to_string(),
        out_dir.to_string_lossy().to_string(),
        "--data-home".to_string(),
        data_home.to_string_lossy().to_string(),
    ]);
    let output = run_node(
        &repo,
        "packages/city-game-sdk/scripts/buildGame.ts",
        &runner_args,
    )?;
    // 墙钟预算耗尽是**正常失败结果**（见文件头）：status=failed + 结构化
    // diagnostics（预算 + 输出尾部），Agent 可以据此收缩输入重试，而不是收到
    // ToolError 断掉修复回路。
    if output.timed_out {
        let mut data = json!({
            "status": "failed",
            "workspaceId": workspace_id,
            "gameRevision": revision,
            "buildId": Value::Null,
            "diagnostics": [json!({
                "code": "game_execution_timeout",
                "severity": "error",
                "stage": "build",
                "message": format!("The build runner exceeded its {}s wall-clock budget and was killed.{}", RUNNER_BUILD_BUDGET_SECS, runner_output_tail(&output)),
            })],
        });
        if let Some(target) = &candidate {
            data["candidateId"] = json!(target.candidate_id);
        }
        return Ok(json!({"ok":true,"data":data}));
    }
    let parsed: Value = serde_json::from_slice(&output.stdout)
        .map_err(|_| if output.stdout_truncated {
            ToolError::new("game_build_failed", "The build runner output exceeded the 256 KiB collection cap before a JSON result was produced.")
        } else {
            ToolError::new("data_unavailable", "The build runner returned no JSON result.")
        })?;
    let data = if parsed.get("ok").and_then(Value::as_bool) == Some(true) {
        let build_id = build_id_arg(&parsed)?;
        if let Some(target) = &candidate {
            let sealed = super::creator_code_candidate::build_candidate_revision(
                data_home,
                &build_id,
                &target.candidate_id,
                &meta.game_id,
            )?;
            if sealed != target.revision {
                return Err(ToolError::new("workspace_revision_conflict", "The sealed build does not match the requested source revision."));
            }
            super::creator_code_candidate::note_build(data_home, &target.candidate_id, &build_id)?;
        } else {
            let sealed = build_workspace_revision(data_home, &build_id, &meta)?;
            if sealed != meta.revision {
                return Err(ToolError::new("workspace_revision_conflict", "The sealed build does not match the requested source revision."));
            }
        }
        let mut data = json!({
            "status": "succeeded",
            "workspaceId": workspace_id,
            "gameRevision": revision,
            "buildId": build_id,
            "byteLength": parsed.get("byteLength").cloned().unwrap_or(Value::Null),
            "diagnostics": parsed.get("warnings").cloned().unwrap_or_else(|| json!([])),
        });
        if let Some(target) = &candidate {
            data["candidateId"] = json!(target.candidate_id);
        }
        data
    } else {
        let mut data = json!({
            "status": "failed",
            "workspaceId": workspace_id,
            "gameRevision": revision,
            "buildId": Value::Null,
            "diagnostics": parsed.get("diagnostics").cloned().unwrap_or_else(|| json!([])),
        });
        if let Some(target) = &candidate {
            data["candidateId"] = json!(target.candidate_id);
        }
        data
    };
    Ok(json!({"ok":true,"data":data}))
}

/// The MCP process and City WebView share only a bounded request document.
/// Frozen build bytes stay in the data home and are verified by the desktop host.
fn stage_preview(args: &Value, data_home: &Path) -> Result<Value, ToolError> {
    let workspace_id = workspace_id_arg(args)?;
    let build_id = build_id_arg(args)?;
    let seed = args.get("seed").and_then(Value::as_u64).unwrap_or(7);
    let directory = workspace_dir(data_home, &workspace_id)?;
    let meta = read_meta(&directory)?;
    let revision = build_workspace_revision(data_home, &build_id, &meta)?;
    let root = data_home.join("state/creator/code-games");
    let previews = root.join("previews");
    std::fs::create_dir_all(&previews).map_err(|_| ToolError::new("storage_unavailable", "Cannot create the preview request directory."))?;
    let created = now_ms();
    let request_id = format!("preview-{build_id}-{created}");
    let preview_id = format!("preview-{}", random_hex(16));
    let mut request = json!({"requestId":request_id,"previewId":preview_id,"buildId":build_id,"seed":seed,
        "source":{"cityId":"city:preview-fixture","seed":7,"synthetic":true},"status":"queued","createdAtMs":created});
    if let Some(city_id) = args.get("cityId").and_then(Value::as_str) {
        if city_id.is_empty() || city_id.len() > 128 { return Err(ToolError::new("invalid_argument", "cityId is invalid")); }
        request["source"] = json!({"cityId":city_id});
    }
    let directory = previews.join(&preview_id);
    std::fs::create_dir(&directory).map_err(|_| ToolError::new("storage_unavailable", "Cannot allocate an independent preview request."))?;
    let temporary = directory.join("request.json.tmp");
    let target = directory.join("request.json");
    std::fs::write(&temporary, serde_json::to_vec(&request).map_err(|_| ToolError::new("internal_error", "Cannot encode the preview request."))?)
        .map_err(|_| ToolError::new("storage_unavailable", "Cannot write the preview request."))?;
    std::fs::rename(&temporary, &target).map_err(|_| ToolError::new("storage_unavailable", "Cannot publish the preview request."))?;
    Ok(json!({"ok":true,"data":{"workspaceId":workspace_id,"gameId":meta.game_id,"buildId":build_id,"seed":seed,
        "requestId":request_id,"previewId":preview_id,"gameRevision":revision,"status":"queued"}}))
}

fn build_id_arg(args: &Value) -> Result<String, ToolError> {
    let value = required_str(args, "buildId", 64)?;
    if value.len() != 64 || !value.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()) {
        return Err(ToolError::new("invalid_argument", "`buildId` must be a 64-character lower-case hex digest"));
    }
    Ok(value)
}

/// The builder seals sourceRevision into the immutable build ID. Workspace-scoped
/// consumers accept an older revision of the same workspace for reproducible tests.
pub(crate) fn build_workspace_revision(data_home: &Path, build_id: &str, meta: &WorkspaceMeta) -> Result<String, ToolError> {
    use std::io::Read;
    let directory = data_home.join("code-games").join("builds").join(build_id);
    if !directory.join("game.js").is_file() || !directory.join("manifest.json").is_file() {
        return Err(ToolError::new("not_found", "No sealed build for that buildId in this data home."));
    }
    let file = std::fs::File::open(directory.join("build.json"))
        .map_err(|_| ToolError::new("not_found", "The sealed build record is unavailable."))?;
    let mut bytes = Vec::new();
    file.take(MAX_FILE_BYTES as u64 + 1).read_to_end(&mut bytes)
        .map_err(|_| ToolError::new("game_build_failed", "Cannot read the sealed build record."))?;
    let record: Value = serde_json::from_slice(&bytes)
        .map_err(|_| ToolError::new("game_build_failed", "The sealed build record is malformed."))?;
    let prefix = format!("workspace:{}:", meta.workspace_id);
    let revision = record["sourceRevision"].as_str()
        .and_then(|source| source.strip_prefix(&prefix))
        .filter(|value| value.len() == 64 && value.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()));
    if let Some(revision) = revision {
        if bytes.len() <= MAX_FILE_BYTES && record["buildId"] == build_id && record["gameId"] == meta.game_id {
            return Ok(revision.to_owned());
        }
    }
    Err(ToolError::new("workspace_build_mismatch", "This build is not attributed to this workspace. Build the workspace again and use the returned buildId."))
}

pub(crate) struct WorkspaceBuildSnapshot {
    pub(crate) path: PathBuf,
}

impl WorkspaceBuildSnapshot {
    pub(crate) fn capture(directory: &Path, revision: &str) -> Result<Self, ToolError> {
        let files = list_files(directory)?;
        let total_bytes = files.iter().map(|(_, bytes)| *bytes).sum::<u64>();
        if total_bytes > MAX_SNAPSHOT_BYTES {
            return Err(ToolError::new("invalid_argument", "The Code Game workspace exceeds the build input byte budget."));
        }
        let path = std::env::temp_dir().join(format!("oh-code-build-{}", random_hex(32)));
        let mut directory_builder = std::fs::DirBuilder::new();
        #[cfg(unix)]
        {
            use std::os::unix::fs::DirBuilderExt;
            directory_builder.mode(0o700);
        }
        directory_builder.create(&path)
            .map_err(|_| ToolError::new("storage_unavailable", "Cannot create the Code Game build input."))?;
        let snapshot = Self { path };
        for (relative, _) in files {
            let source = resolve_inside(directory, &relative)?;
            let target = snapshot.path.join(relative);
            if let Some(parent) = target.parent() {
                std::fs::create_dir_all(parent)
                    .map_err(|_| ToolError::new("storage_unavailable", "Cannot stage a Code Game build input."))?;
            }
            std::fs::copy(source, target)
                .map_err(|_| ToolError::new("storage_unavailable", "Cannot stage a Code Game build input."))?;
        }
        if digest_workspace(&snapshot.path)? != revision {
            return Err(ToolError::new("workspace_revision_conflict", "Code Game source changed before the build. Refresh the workspace revision and retry."));
        }
        Ok(snapshot)
    }
}

impl Drop for WorkspaceBuildSnapshot {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

fn code_test(args: &Value, data_home: &Path) -> Result<Value, ToolError> {
    let workspace_id = workspace_id_arg(args)?;
    let build_id = build_id_arg(args)?;
    let seed = args.get("seed").and_then(Value::as_u64).unwrap_or(7);
    let ticks = args.get("ticks").and_then(Value::as_u64).unwrap_or(600);
    if ticks == 0 || ticks > MAX_TICKS {
        return Err(ToolError::new("invalid_argument", format!("`ticks` must be from 1 to {MAX_TICKS}")));
    }
    // 场景（PR06）：inline JSON 透传给 runner，MCP 只做小形状检查（长度上限 +
    // closed kind 词表），深度逐字段校验留在 runner。无效场景是 invalid_argument，
    // 绝不带病运行再静默忽略。
    let scenario = code_test_scenario(args)?;
    // 测试源显式化（PR05）：cityId+cityRevision 成对给出 → 宿主冻结的 City 快照；
    // 都不给 → 合成 fixture。解析失败是结构化非可执行诊断，绝不静默回退合成世界。
    let city_snapshot = code_test_city_source(args, data_home)?;
    let meta = read_meta(&workspace_dir(data_home, &workspace_id)?)?;
    // PR09 候选隔离层：可选 `candidateId`——buildId 必须密封该候选的摘要
    // （`candidate:<candidateId>:<digest>`），否则拒绝；缺席时保持基线校验。
    let candidate = super::creator_code_candidate::test_target(args, data_home, &workspace_id, &build_id, &meta.game_id)?;
    let revision = match &candidate {
        Some(target) => target.revision.clone(),
        None => build_workspace_revision(data_home, &build_id, &meta)?,
    };
    if let Some(target) = &candidate {
        super::creator_code_candidate::mark_status(data_home, &target.candidate_id, "testing")?;
    }
    let repo = repo_root()?;
    let mut runner_args = vec![
        "--build".to_string(),
        build_id.to_string(),
        "--builds-dir".to_string(),
        data_home.join("code-games").join("builds").to_string_lossy().to_string(),
        "--seed".to_string(),
        seed.to_string(),
        "--ticks".to_string(),
        ticks.to_string(),
    ];
    if let Some(request) = &scenario {
        runner_args.push("--scenario".to_string());
        runner_args.push(request.raw.clone());
    }
    if let Some(snapshot) = &city_snapshot {
        // City 路径：runner 侧 validateCityWorldSnapshot + header.snapshotDigest
        // 对照是真正的密码学校验执行点；这里只负责把有界暂存的快照与 digest 交给它。
        runner_args.push("--snapshot".to_string());
        runner_args.push(snapshot.staged_path.to_string_lossy().to_string());
        runner_args.push("--snapshot-digest".to_string());
        runner_args.push(snapshot.digest.clone());
    }
    let output = run_node_with_limits(
        &repo,
        "packages/city-game-sdk/scripts/previewGame.ts",
        &runner_args,
        &NodeRunLimits::test(),
    )?;
    // 与脚本自身的 `game_execution_timeout`（previewGame 的墙钟 deadline）同码：
    // 无头运行有界是 creator_code_test 既有响应形态的一部分——失败按 ToolError
    // 映射稳定错误码，绝不静默成功，也绝不挂死工具调用。PR06：失败路径同时落一条
    // executionOk=false + verdict=failed 的门记录（执行失败永远不等于测试通过）。
    if output.timed_out {
        let source = code_test_source_record(city_snapshot.as_ref(), &Value::Null);
        let verdict = code_test_failure_verdict(scenario.as_ref(), "runner_timeout");
        write_test_record(data_home, &build_id, &revision, seed, ticks, &CodeTestOutcome { ok: false, source: &source, verdict: &verdict }, candidate.as_ref().map(|target| target.candidate_id.as_str()))?;
        return Err(ToolError::new(
            "game_execution_timeout",
            format!(
                "The headless run exceeded its {}s wall-clock budget; the runner was killed.{}",
                RUNNER_TEST_BUDGET_SECS, runner_output_tail(&output)
            ),
        ));
    }
    let parsed: Value = match serde_json::from_slice(&output.stdout) {
        Ok(parsed) => parsed,
        // runner 跑了但没有可解析结果：同样是一条 ok:false 的门记录，再结构化报错。
        Err(_) => {
            let source = code_test_source_record(city_snapshot.as_ref(), &Value::Null);
            let verdict = code_test_failure_verdict(scenario.as_ref(), "runner_output_invalid");
            write_test_record(data_home, &build_id, &revision, seed, ticks, &CodeTestOutcome { ok: false, source: &source, verdict: &verdict }, candidate.as_ref().map(|target| target.candidate_id.as_str()))?;
            return Err(ToolError::new("data_unavailable", "The headless runner returned no JSON result."));
        }
    };
    if parsed.get("ok").and_then(Value::as_bool) != Some(true) {
        let code: &'static str = match parsed.get("error").and_then(|error| error.get("code")).and_then(Value::as_str) {
            Some("game_entry_invalid") => "game_entry_invalid",
            Some("game_asset_invalid") => "game_asset_invalid",
            Some("game_permission_denied") => "game_permission_denied",
            Some("game_argument_invalid") => "game_argument_invalid",
            Some("game_world_object_missing") => "game_world_object_missing",
            Some("game_execution_timeout") => "game_execution_timeout",
            // City 快照路径（PR05）：digest 不符是 runner 的执行点在把关，原样透出。
            Some("game_package_integrity_failed") => "game_package_integrity_failed",
            Some("game_manifest_unsupported") => "game_manifest_unsupported",
            _ => "game_runtime_fault",
        };
        let message = parsed.get("error").and_then(|error| error.get("message")).and_then(Value::as_str).unwrap_or("The headless run failed.");
        let source = code_test_source_record(city_snapshot.as_ref(), &Value::Null);
        let verdict = code_test_failure_verdict(scenario.as_ref(), "runner_failed");
        write_test_record(data_home, &build_id, &revision, seed, ticks, &CodeTestOutcome { ok: false, source: &source, verdict: &verdict }, candidate.as_ref().map(|target| target.candidate_id.as_str()))?;
        return Err(ToolError::new(code, message.to_string()));
    }
    let telemetry = parsed.get("telemetry").cloned().unwrap_or(Value::Null);
    let source = code_test_source_record(city_snapshot.as_ref(), &telemetry);
    let verdict = code_test_success_verdict(scenario.as_ref(), parsed.get("scenario"), city_snapshot.as_ref(), &telemetry);
    write_test_record(data_home, &build_id, &revision, seed, ticks, &CodeTestOutcome { ok: true, source: &source, verdict: &verdict }, candidate.as_ref().map(|target| target.candidate_id.as_str()))?;
    // PR06：data 增加 executionOk/verdict/scenarioId?/assertions?/worldSnapshotDigest?
    // （verdict 恒存在：无场景 → inconclusive + verdictReason=no_scenario，消费方
    // 无需处理缺失分支）。
    let mut data = serde_json::Map::new();
    data.insert("workspaceId".into(), json!(workspace_id));
    data.insert("gameId".into(), json!(meta.game_id));
    data.insert("buildId".into(), json!(build_id));
    data.insert("gameRevision".into(), json!(revision));
    if let Some(target) = &candidate {
        data.insert("candidateId".into(), json!(target.candidate_id));
    }
    data.insert("source".into(), source);
    data.insert("telemetry".into(), telemetry);
    if let Some(extras) = verdict.as_object() {
        for (key, value) in extras {
            data.insert(key.clone(), value.clone());
        }
    }
    Ok(json!({"ok":true,"data":data}))
}

// ── Scenario / Verdict（PR06）───────────────────────────────────────

/// 一次 code_test 的执行结论：runner 是否跑完（executionOk 同源）、来源声明
/// 与裁决块（executionOk/verdict/verdictReason/scenarioId?/assertions?/
/// worldSnapshotDigest?）。响应与门记录共用同一形状。
pub(crate) struct CodeTestOutcome<'a> {
    pub(crate) ok: bool,
    pub(crate) source: &'a Value,
    pub(crate) verdict: &'a Value,
}

/// MCP 侧最大场景 JSON 与 runner（MAX_SCENARIO_JSON=8192）对齐。
const MAX_SCENARIO_JSON: usize = 8_192;
/// closed 断言词表（与 SDK `GAME_TEST_ASSERTION_KINDS_V1` 同表；深度校验在 runner）。
const SCENARIO_ASSERTION_KINDS: [&str; 7] = [
    "outcome",
    "entityCountAtLeast",
    "entityCountAtMost",
    "hudFlag",
    "counterAtLeast",
    "counterEquals",
    "finishedWithinTicks",
];

/// 一次 code_test 请求携带的场景：原始 inline JSON（透传）+ 已复核的 scenarioId。
#[derive(Debug)]
struct CodeTestScenario {
    raw: String,
    scenario_id: String,
}

/// 小形状检查：≤8 KiB inline JSON、schemaVersion 1、scenarioId ≤128、断言
/// 1..8 且每条有 ≤64 的 id 与 closed kind。字段级 cap/counter 词表由 runner
/// 的 validateGameTestScenarioV1 负责并返回逐字段诊断。
fn code_test_scenario(args: &Value) -> Result<Option<CodeTestScenario>, ToolError> {
    let Some(raw) = args.get("scenario").and_then(Value::as_str) else {
        return Ok(None);
    };
    if raw.is_empty() || raw.len() > MAX_SCENARIO_JSON {
        return Err(ToolError::new(
            "invalid_argument",
            format!("`scenario` must be inline JSON of at most {MAX_SCENARIO_JSON} bytes"),
        ));
    }
    let parsed: Value = serde_json::from_str(raw)
        .map_err(|_| ToolError::new("invalid_argument", "`scenario` is not valid JSON."))?;
    if parsed.get("schemaVersion").and_then(Value::as_u64) != Some(1) {
        return Err(ToolError::new("invalid_argument", "`scenario` schemaVersion must be 1."));
    }
    let scenario_id = parsed
        .get("scenarioId")
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty() && value.len() <= 128)
        .ok_or_else(|| ToolError::new("invalid_argument", "`scenario.scenarioId` must be 1..128 characters."))?;
    let assertions = parsed
        .get("assertions")
        .and_then(Value::as_array)
        .filter(|items| !items.is_empty() && items.len() <= 8)
        .ok_or_else(|| ToolError::new("invalid_argument", "`scenario.assertions` must be an array of 1..8 assertions."))?;
    for assertion in assertions {
        assertion
            .get("id")
            .and_then(Value::as_str)
            .filter(|value| !value.is_empty() && value.len() <= 64)
            .ok_or_else(|| ToolError::new("invalid_argument", "each `scenario.assertions[]` needs an id of 1..64 characters."))?;
        assertion
            .get("kind")
            .and_then(Value::as_str)
            .filter(|kind| SCENARIO_ASSERTION_KINDS.contains(kind))
            .ok_or_else(|| ToolError::new(
                "invalid_argument",
                format!("each `scenario.assertions[].kind` must be one of: {}", SCENARIO_ASSERTION_KINDS.join(", ")),
            ))?;
    }
    Ok(Some(CodeTestScenario { raw: raw.to_string(), scenario_id: scenario_id.to_owned() }))
}

/// 失败路径（runner 超时 / 输出不可解析 / runner 报错）的裁决块：执行失败
/// 永远 verdict=failed，绝不 inconclusive、更不可能 passed。
fn code_test_failure_verdict(scenario: Option<&CodeTestScenario>, reason: &str) -> Value {
    let mut extras = serde_json::Map::new();
    extras.insert("executionOk".into(), json!(false));
    extras.insert("verdict".into(), json!("failed"));
    extras.insert("verdictReason".into(), json!(reason));
    if let Some(request) = scenario {
        extras.insert("scenarioId".into(), json!(request.scenario_id));
    }
    Value::Object(extras)
}

/// 成功路径裁决（与 SDK `evaluateGameTestScenarioV1` 的决策表同源，这里是
/// MCP 对 runner 输出的采信 + 自洽复核）：
/// - 未请求场景 → `inconclusive` + `no_scenario`（显式值，消费方无需处理缺失）；
/// - 请求了场景但 runner 没给场景块（太老的 runner）→ `inconclusive` + `runner_too_old`；
/// - 场景块存在 → 采信 runner 的 verdict/reason/断言；但 `passed` 从不自夸：
///   runner 声称 passed 而任一断言不是 passed，或回块的 scenarioId 与请求不符
///   → 降级 `inconclusive` + `unresolved_assertions`；
/// - City 路径附带 `worldSnapshotDigest`（runner telemetry 回显优先，宿主冻结
///   digest 兜底；合成路径无世界摘要，字段缺席）。
fn code_test_success_verdict(
    scenario: Option<&CodeTestScenario>,
    scenario_block: Option<&Value>,
    city_snapshot: Option<&CityTestSnapshot>,
    telemetry: &Value,
) -> Value {
    let mut extras = serde_json::Map::new();
    extras.insert("executionOk".into(), json!(true));
    let world_snapshot_digest = telemetry
        .get("snapshotDigest")
        .and_then(Value::as_str)
        .map(ToString::to_string)
        .or_else(|| city_snapshot.map(|snapshot| snapshot.digest.clone()));
    if let Some(digest) = world_snapshot_digest {
        extras.insert("worldSnapshotDigest".into(), json!(digest));
    }
    let (Some(request), Some(block)) = (scenario, scenario_block) else {
        if let Some(request) = scenario {
            // 请求了场景但 runner 没给场景块（太老的 runner）。
            extras.insert("scenarioId".into(), json!(request.scenario_id));
            extras.insert("verdict".into(), json!("inconclusive"));
            extras.insert("verdictReason".into(), json!("runner_too_old"));
        } else {
            extras.insert("verdict".into(), json!("inconclusive"));
            extras.insert("verdictReason".into(), json!("no_scenario"));
        }
        return Value::Object(extras);
    };
    extras.insert("scenarioId".into(), json!(request.scenario_id));
    let Some(block) = block.as_object() else {
        extras.insert("verdict".into(), json!("inconclusive"));
        extras.insert("verdictReason".into(), json!("runner_too_old"));
        return Value::Object(extras);
    };
    let verdict = block.get("verdict").and_then(Value::as_str)
        .filter(|value| matches!(*value, "passed" | "failed" | "inconclusive"));
    let assertions = block.get("assertions").and_then(Value::as_array)
        .filter(|items| items.iter().all(|item| item.get("id").and_then(Value::as_str).is_some() && item.get("status").and_then(Value::as_str).is_some()));
    let all_assertions_passed = assertions
        .map(|items| !items.is_empty() && items.iter().all(|item| item.get("status").and_then(Value::as_str) == Some("passed")))
        .unwrap_or(false);
    // 自洽复核：`passed` 需要场景身份一致 + 断言全过（断言块不得为空）；
    // 否则降级 inconclusive。
    let consistent = block.get("scenarioId").and_then(Value::as_str) == Some(request.scenario_id.as_str())
        && assertions.is_some()
        && (!matches!(verdict, Some("passed")) || all_assertions_passed);
    let (verdict, reason) = match (verdict, consistent) {
        (Some("passed"), true) => ("passed", None),
        (Some(v), true) => (v, block.get("verdictReason").and_then(Value::as_str)),
        _ => ("inconclusive", Some("unresolved_assertions")),
    };
    extras.insert("verdict".into(), json!(verdict));
    if let Some(reason) = reason.filter(|_| verdict != "passed") {
        extras.insert("verdictReason".into(), json!(reason));
    }
    if let Some(items) = assertions {
        extras.insert("assertions".into(), json!(items.iter().take(8).cloned().collect::<Vec<_>>()));
    }
    Value::Object(extras)
}

