/// 统一创作模板目录（PR12 §6.1）：生成的 Code Game 模板索引。project_create 的
/// 模板词表从固定 `hello-city` 改为这份生成索引的 allow list——目录条目只是创作
/// 入口元数据，不是可执行授权：真正的创建仍要求仓库里存在
/// `games/<templateId>/game.manifest.json`，且模板 id 只走固定 join（无用户路径）。
const CODE_TEMPLATE_INDEX_JSON: &str =
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../assets/creator/code-templates-index.json"));

fn code_template_index() -> &'static Value {
    static INDEX: std::sync::OnceLock<Value> = std::sync::OnceLock::new();
    INDEX.get_or_init(|| serde_json::from_str(CODE_TEMPLATE_INDEX_JSON)
        .expect("assets/creator/code-templates-index.json must parse (generated by scripts/generate-creator-capabilities.mjs)"))
}

/// 注册的 Code Game 模板条目。索引在生成期已校验 id/entry 形状，这里再做一次
/// 纵深防御：`source.entry` 必须恰好是 `games/<templateId>`（拒绝任何形式的
/// 路径逃逸，`..`、绝对路径、子目录都不可能通过）。
fn code_template_entry(template: &str) -> Option<&'static Value> {
    let templates = code_template_index().get("templates").and_then(Value::as_array)?;
    let entry = templates.iter().find(|entry| entry.get("templateId").and_then(Value::as_str) == Some(template))?;
    let matches = entry.get("source").and_then(|source| source.get("entry")).and_then(Value::as_str)
        == Some(format!("games/{template}").as_str());
    matches.then_some(entry)
}

/// 已注册模板 id 列表（unknown 错误的可执行恢复建议）。
fn code_template_ids() -> Vec<&'static str> {
    code_template_index().get("templates").and_then(Value::as_array).map(|templates| {
        templates.iter().filter_map(|entry| entry.get("templateId").and_then(Value::as_str)).collect()
    }).unwrap_or_default()
}

/// 模板 id 词表（先于任何路径使用）：小写字母/数字开头，后续允许 `-`。
/// 绝不允许 `..`、`/`、`\`、`:` 或绝对路径——允许列表之外的一切都会先在这里拒绝。
fn valid_template_id(value: &str) -> bool {
    !value.is_empty() && value.len() <= 64
        && value.starts_with(|c: char| c.is_ascii_lowercase() || c.is_ascii_digit())
        && value.bytes().all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

