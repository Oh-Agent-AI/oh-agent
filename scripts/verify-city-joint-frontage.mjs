#!/usr/bin/env node
// Joint-pose regression; does not certify the complete physical-model rollout.
import assert from "node:assert/strict";
import { loadCity } from "./city-kit/index.mjs";
const { emptyNetwork, addNetworkEdge, assignConnectedSite, specByKind, JOINT_SITE_CONFIG } = await loadCity({
  "engine/planner/network.ts": ["emptyNetwork", "addNetworkEdge"],
  "engine/planner/jointSite.ts": ["assignConnectedSite", "JOINT_SITE_CONFIG"],
  "engine/planner/sitespec.ts": ["specByKind"],
});
for (const turns of [0, 1, 2, 3]) {
  const transform = (x, z) => { for (let i = 0; i < turns; i++) [x, z] = [-z, x]; return { x, z }; };
  const inverse = (x, z) => { for (let i = 0; i < turns; i++) [x, z] = [z, -x]; return { x, z }; };
  const network = emptyNetwork();
  for (const [a, b] of [[[-100, 0], [100, 0]], [[100, 0], [200, 0]], [[200, 0], [200, 100]],
    [[200, 100], [30, 100]], [[30, 32], [30, 100]]]) addNetworkEdge(network, transform(...a), transform(...b), true);
  const a = transform(30, 32), b = transform(30, 100);
  const nearId = [`${a.x}:${a.z}`, `${b.x}:${b.z}`].sort().join("/");
  // An accepted approach can legally cross the non-building setback zone;
  // an ordinary new frontage connector cannot. It must not steal the gate
  // direction of a position generated by a different, valid host road.
  network.edges.get(nearId).structure = "ground-approach";
  const buildable = (x, z) => { const q = inverse(x, z); return !(q.x > 26 && q.x < 29 && q.z > 25 && q.z < 40); };
  const p = (x, z) => ({ x, z });
  const world = { core: p(0, 0), R: 1000, turn: 0, coast: [], trunkRuns: [], ringRuns: [], bridges: [], placed: [],
    height: () => 1.2, inRiver: () => false, riverBank: () => false, coastDistance: () => 1000,
    landClearance: () => 1000, buildable, hasRiver: false, riverX: () => 9999, riverWidth: () => 0,
    hillDir: p(0, 1), hillLine: 9999, hillProj: () => 0 };
  const connector = { network, geo: { height: world.height, buildable, terrain: { slope: () => 0 } },
    inRiver: world.inRiver, reservations: () => [] };
  const anchor = transform(-100, 0), desired = transform(0, 32), gate = transform(0, 4);
  const before = JSON.stringify({ nodes: [...network.nodes], edges: [...network.edges] });
  const spec = { ...specByKind("station"), kind: "renamed-model", radius: 20 };
  const result = assignConnectedSite(world, connector, spec, "required-owner", `${anchor.x}:${anchor.z}`,
    (site) => site.x === desired.x && site.z === desired.z ? null : "different-programme-position");
  assert.ok(result.site, result.reason);
  assert.equal(result.site.access.nodeId, `${gate.x}:${gate.z}`, "recover the actual generating frontage, not the closer impassable pose");
  assert.ok(result.routeRetries > 0 && result.rejected <= JOINT_SITE_CONFIG.maxCandidateEvaluations);
  assert.equal(result.site.access.capability, "ground-frontage");
  assert.equal(JSON.stringify({ nodes: [...network.nodes], edges: [...network.edges] }), before,
    "proposal cannot publish, delete, narrow or relocate existing roads");
  for (const [id, edge] of network.edges) {
    if (result.network.edges.has(id)) { assert.deepEqual(result.network.edges.get(id), edge); continue; }
    const middle = transform(0, 0);
    const middleId = `${middle.x}:${middle.z}`;
    const childIds = [[edge.from, middleId], [middleId, edge.to]].map((pair) => pair.sort().join("/"));
    for (const childId of childIds) {
      const child = result.network.edges.get(childId);
      assert.ok(child, "splitting the host must preserve both original half-corridors");
      assert.equal(child.width, edge.width);
      assert.equal(child.kind, edge.kind);
      assert.equal(child.structure, edge.structure);
    }
  }
}
console.log("City joint frontage: 4 transformed actual-host pose recoveries passed within the original candidate bound.");
